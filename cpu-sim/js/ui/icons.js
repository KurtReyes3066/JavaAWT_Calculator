export function icon(name, cls = '') {
  const body = P[name];
  if (!body) return '';
  return `<svg class="ico ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="square" stroke-linejoin="miter" aria-hidden="true" focusable="false">${body}</svg>`;
}

/** Replaces every [data-icon] placeholder inside root with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.hydrated === el.dataset.icon) return;
    el.innerHTML = icon(el.dataset.icon);
    el.dataset.hydrated = el.dataset.icon;
  });
}
